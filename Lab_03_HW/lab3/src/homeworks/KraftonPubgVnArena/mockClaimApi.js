/**
 * Error thrown by the mock claim API, carrying an HTTP-like status.
 */
export class ClaimApiError extends Error {
  /**
   * @param {number} status
   * @param {string} code
   * @param {string} message
   */
  constructor(status, code, message) {
    super(message);
    this.name = 'ClaimApiError';
    this.status = status;
    this.code = code;
  }
}

/**
 * Creates an in-memory claim server with its own inventory.
 * @param {ReadonlyArray<import('./contract.js').CrateDrop>} drops
 * @param {{ latencyMs?: number }} [options]
 */
export function createMockClaimApi(drops, { latencyMs = 800 } = {}) {
  const serverStock = new Map(drops.map((drop) => [drop.id, drop.remainingStock]));
  const dropWindows = new Map(
    drops.map((drop) => [drop.id, { dropEpochMs: drop.dropEpochMs, expireEpochMs: drop.expireEpochMs }]),
  );
  const settledClaims = new Map();

  const processClaim = (dropId, claimId) => {
    if (settledClaims.has(claimId)) return settledClaims.get(claimId);

    const dropWindow = dropWindows.get(dropId);
    if (!dropWindow) {
      throw new ClaimApiError(404, 'DROP_NOT_FOUND', 'Airdrop not found.');
    }

    const nowMs = Date.now();
    if (nowMs < dropWindow.dropEpochMs || nowMs >= dropWindow.expireEpochMs) {
      throw new ClaimApiError(422, 'DROP_NOT_LIVE', 'Airdrop is not live.');
    }

    const stock = serverStock.get(dropId);
    if (stock <= 0) {
      throw new ClaimApiError(409, 'LOOTED_OUT', 'Looted out: no stock left.');
    }

    serverStock.set(dropId, stock - 1);
    const result = Object.freeze({ claimId, dropId, remainingStock: stock - 1 });
    settledClaims.set(claimId, result);
    return result;
  };

  /**
   * @param {string} dropId
   * @param {string} claimId Idempotency key generated by the client.
   * @param {{ signal?: AbortSignal }} [options]
   * @returns {Promise<{ claimId: string, dropId: string, remainingStock: number }>}
   */
  const claim = (dropId, claimId, { signal } = {}) =>
    new Promise((resolve, reject) => {
      if (signal?.aborted) {
        reject(signal.reason);
        return;
      }

      const onAbort = () => {
        clearTimeout(timerId);
        reject(signal.reason);
      };

      const timerId = setTimeout(() => {
        signal?.removeEventListener('abort', onAbort);
        try {
          resolve(processClaim(dropId, claimId));
        } catch (error) {
          reject(error);
        }
      }, latencyMs);

      signal?.addEventListener('abort', onAbort, { once: true });
    });

  /** Test helper: other players loot units directly on the server. */
  const simulateRivalLoot = (dropId, quantity = 1) => {
    const stock = serverStock.get(dropId) ?? 0;
    const nextStock = Math.max(0, stock - quantity);
    serverStock.set(dropId, nextStock);
    return nextStock;
  };

  const getServerStock = (dropId) => serverStock.get(dropId);

  return Object.freeze({ claim, simulateRivalLoot, getServerStock });
}